#!/bin/bash
# testrig-dell-net.sh — persistent data-plane networking for the ASK2 test rig dells (2026-10-09).
# Run ON dell1 or dell2 as root: `sudo bash testrig-dell-net.sh dell1|dell2`. Idempotent.
#
# Wiring (verified by MAC 2026-10-09):
#   dell1 X710 p1 enp1s0f0np0 -> .185 eth3     dell2 X710 p1 enp1s0f0np0 -> .185 eth4
#   dell1 X710 p2 enp1s0f1np1 -> .106 eth3     dell2 X710 p2 enp1s0f1np1 -> .106 eth4
#   dell1 ConnectX-3 enp2s0 <-> dell2 ConnectX-3 enp2s0   (direct, no DUT)
# .185 and .106 use the same data-plane addresses, so the .185 paths live in the root namespace
# (NetworkManager profiles) and the .106 paths in netns n106 (systemd unit), with identical
# addresses. Run .106 tests as `sudo ip netns exec n106 ...`. Management (enp0s31f6,
# "Wired connection 1") is never touched.
set -eu
ROLE=${1:?usage: testrig-dell-net.sh dell1|dell2}
P1=enp1s0f0np0; P2=enp1s0f1np1; DIRECT=enp2s0
case $ROLE in
  dell1) ME=112; LAN=1;  VID=10; GW=1;  PEER=2;  PEERV=20; TBL=110; PRIO=11000
         # dell1 also reaches dell2's VLAN only through its own VLAN (vlan-vlan combo).
         ;;
  dell2) ME=113; LAN=2;  VID=20; GW=2;  PEER=1;  PEERV=10; TBL=120; PRIO=12000 ;;
  *) echo "role must be dell1 or dell2"; exit 2 ;;
esac
V=$P1.$VID; VN=$P2.$VID   # VLAN on the root (.185) and n106 (.106) port

# --- NIC tuning, applied at every device add (boot) and now ----------------------------------
cat > /etc/udev/rules.d/80-lab-nic-tune.rules <<'EOF'
# ASK2 test rig: bigger rings; X710 firmware LLDP agent off (it consumes LLDP and can reset links).
ACTION=="add", SUBSYSTEM=="net", DRIVERS=="i40e", RUN+="/usr/sbin/ethtool -G $name rx 4096 tx 4096", RUN+="/usr/sbin/ethtool --set-priv-flags $name disable-fw-lldp on"
ACTION=="add", SUBSYSTEM=="net", DRIVERS=="mlx4_core", RUN+="/usr/sbin/ethtool -G $name rx 4096 tx 4096"
EOF
for i in $P1 $P2; do
  ip link show $i >/dev/null 2>&1 || continue
  ethtool -G $i rx 4096 tx 4096 2>/dev/null || true
  ethtool --set-priv-flags $i disable-fw-lldp on 2>/dev/null || true
done
ip netns exec n106 true 2>/dev/null && ip netns exec n106 ethtool -G $P2 rx 4096 tx 4096 2>/dev/null || true
ethtool -G $DIRECT rx 4096 tx 4096 2>/dev/null || true
# IOMMU passthrough: Debian boots DMA-translated (DMA-FQ), which caps kernel pktgen on the X710 at
# ~3-4 Mpps (64 B line rate is 14.88 Mpps). VFIO still works with iommu=pt.
grep -q 'iommu=pt' /etc/default/grub || {
  sed -i 's/^GRUB_CMDLINE_LINUX_DEFAULT="/&iommu=pt /' /etc/default/grub && update-grub
  echo "$ROLE: iommu=pt added to the kernel command line, reboot required"; }

# --- NetworkManager: never touch the n106 port; root-namespace profiles ------------------------
cat > /etc/NetworkManager/conf.d/91-lab-unmanaged.conf <<EOF
[keyfile]
unmanaged-devices=interface-name:$P2;interface-name:$P2.$VID
EOF
nmcli general reload conf
for c in mellanox-enp1s0 vlan10 vlan20 enp2s0 lab-185-p1 lab-185-vlan lab-direct; do
  nmcli -t -f NAME con show | grep -qx "$c" && nmcli con delete "$c" >/dev/null
done

if [ $ROLE = dell1 ]; then
  R4="10.99.2.0/24 10.99.1.185"; R6="fd99:2::/64 fd99:1::185"
  VR4="10.99.20.0/24 10.99.10.185, 10.99.2.0/24 10.99.10.185 table=$TBL, 10.99.20.0/24 10.99.10.185 table=$TBL"
  VR6="fd99:20::/64 fd99:10::185, fd99:2::/64 fd99:10::185 table=$TBL, fd99:20::/64 fd99:10::185 table=$TBL"
else
  R4="10.99.1.0/24 10.99.2.185, 10.99.10.0/24 10.99.2.185, 10.99.50.0/24 10.99.2.185"
  R6="fd99:1::/64 fd99:2::185, fd99:10::/64 fd99:2::185, fd99:50::/64 fd99:2::185"
  VR4="10.99.10.0/24 10.99.20.185 table=$TBL"
  VR6="fd99:10::/64 fd99:20::185 table=$TBL"
fi
COMMON="ipv4.method manual ipv4.never-default yes ipv4.ignore-auto-dns yes ipv6.method manual ipv6.never-default yes ipv6.ignore-auto-dns yes ipv6.addr-gen-mode eui64 connection.autoconnect yes"
nmcli con add type ethernet con-name lab-185-p1 ifname $P1 $COMMON \
  ipv4.addresses 10.99.$LAN.$ME/24 ipv4.routes "$R4" \
  ipv6.addresses fd99:$LAN::$ME/64 ipv6.routes "$R6" >/dev/null
nmcli con add type vlan con-name lab-185-vlan ifname $V dev $P1 id $VID $COMMON \
  ipv4.addresses 10.99.$VID.$ME/24 ipv4.routes "$VR4" \
  ipv4.routing-rules "priority $PRIO from 10.99.$VID.$ME table $TBL" \
  ipv6.addresses fd99:$VID::$ME/64 ipv6.routes "$VR6" \
  ipv6.routing-rules "priority $PRIO from fd99:$VID::$ME table $TBL" >/dev/null
nmcli con add type ethernet con-name lab-direct ifname $DIRECT $COMMON \
  ipv4.addresses 10.99.99.$ME/24 ipv6.addresses fd99:99::$ME/64 >/dev/null
for c in lab-185-p1 lab-185-vlan lab-direct; do nmcli con up "$c" >/dev/null; done

# --- netns n106: same addressing towards .106 ------------------------------------------------
cat > /usr/local/sbin/lab-n106-setup <<EOF
#!/bin/bash
# Generated by testrig-dell-net.sh ($ROLE). Idempotent; run by lab-n106.service.
set -eu
N=n106
ip netns list | grep -qw \$N || ip netns add \$N
ip link show $P2 >/dev/null 2>&1 && ip link set $P2 netns \$N
X="ip -n \$N"
\$X link set lo up
ip netns exec \$N /usr/sbin/sysctl -q -e -p /etc/sysctl.d/99-network-performance.conf || true
ip netns exec \$N ethtool -G $P2 rx 4096 tx 4096 2>/dev/null || true
\$X link set $P2 up
\$X addr replace 10.99.$LAN.$ME/24 dev $P2
\$X -6 addr replace fd99:$LAN::$ME/64 dev $P2 nodad
\$X link show $VN >/dev/null 2>&1 || \$X link add link $P2 name $VN type vlan id $VID
\$X link set $VN up
\$X addr replace 10.99.$VID.$ME/24 dev $VN
\$X -6 addr replace fd99:$VID::$ME/64 dev $VN nodad
EOF
add_routes(){ # $1 = family flag, $2 = "dst gw[ table=N], ..."
  local fam=$1 spec
  IFS=',' read -ra spec <<<"$2"
  for r in "${spec[@]}"; do set -- $r
    local t=""; [ "${3:-}" ] && t="table ${3#table=}"
    echo "\$X $fam route replace $1 via $2 $t" >> /usr/local/sbin/lab-n106-setup
  done
}
add_routes "" "$R4"; add_routes -6 "$R6"; add_routes "" "$VR4"; add_routes -6 "$VR6"
cat >> /usr/local/sbin/lab-n106-setup <<EOF
\$X rule show | grep -q "from 10.99.$VID.$ME lookup $TBL" || \$X rule add priority $PRIO from 10.99.$VID.$ME table $TBL
\$X -6 rule show | grep -q "from fd99:$VID::$ME lookup $TBL" || \$X -6 rule add priority $PRIO from fd99:$VID::$ME table $TBL
EOF
chmod 755 /usr/local/sbin/lab-n106-setup

cat > /etc/systemd/system/lab-n106.service <<'EOF'
[Unit]
Description=ASK2 test rig: netns n106 with the X710 port facing DUT .106
After=systemd-udev-settle.service NetworkManager.service
Wants=systemd-udev-settle.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/lab-n106-setup

[Install]
WantedBy=multi-user.target
EOF
cat > /etc/systemd/system/lab-n106-iperf3.service <<'EOF'
[Unit]
Description=ASK2 test rig: iperf3 server (5201) inside netns n106
BindsTo=lab-n106.service
After=lab-n106.service

[Service]
User=iperf3
NetworkNamespacePath=/run/netns/n106
ExecStart=/usr/bin/iperf3 --server --interval 0
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF
# iperf2 servers (port 5001, dual-stack) for testrig-combo-matrix.sh: root ns (.185) and n106 (.106).
# Persistent so a dell reboot never leaves the matrix without a server (it used to be nohup'd).
cat > /etc/systemd/system/lab-iperf2.service <<'EOF2'
[Unit]
Description=ASK2 test rig: iperf2 server (5001, -V) in the root namespace
After=network-online.target

[Service]
DynamicUser=yes
ExecStart=/usr/bin/iperf -s -V -p 5001
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF2
sed -e 's/in the root namespace/inside netns n106/' -e '/^After=/a BindsTo=lab-n106.service' \
    -e 's/^After=network-online.target/After=lab-n106.service/' -e '/^DynamicUser/a NetworkNamespacePath=/run/netns/n106' \
    /etc/systemd/system/lab-iperf2.service > /etc/systemd/system/lab-n106-iperf2.service
pkill -f "^iperf -s -V -p 5001" 2>/dev/null || true     # ad-hoc server from older harness runs
systemctl daemon-reload
systemctl enable --now lab-n106.service lab-n106-iperf3.service lab-iperf2.service lab-n106-iperf2.service >/dev/null 2>&1
systemctl restart lab-n106.service

# --- dell1: PPPoE server follows the .185 eth3 port ---------------------------------------------
if [ $ROLE = dell1 ] && [ -f /etc/systemd/system/ask2-pppoe-server.service ]; then
  sed -i "s/ -I [^ ]* / -I $P1 /" /etc/systemd/system/ask2-pppoe-server.service
  systemctl daemon-reload
  systemctl restart ask2-pppoe-server.service
fi
echo "$ROLE: done"
