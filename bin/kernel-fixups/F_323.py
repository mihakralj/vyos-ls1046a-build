apply_one(PCD_INT_H, PCD_INT_H_EDITS)
apply_one(PCD_KG_C, PCD_KG_C_EDITS)
apply_one(PCD_H, PCD_H_EDITS)
apply_one(PCD_C, PCD_C_EDITS)
