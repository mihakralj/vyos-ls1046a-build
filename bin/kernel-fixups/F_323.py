"""F-323: G4 multi-table dispatch via soft-parser $nia + secondary KG schemes.

Implements the production kernel substrate for silicon-proven G4 multi-table
dispatch (2026-11-09, specs/reference/ask2-sp/g4_esp_dispatch.xml):
  - Per-port secondary class tables (rows 1..FMAN_PCD_FE_MAX_CLASSES inside
    each port's existing 256-byte scaffold_gro at FMBM_RCCB + 16*row; zero
    additional MURAM allocation).
  - Top-down KeyGen scheme allocation (31 down, strictly > primary scheme id)
    so the primary routed scheme always wins the match-vector walk for
    unclassified frames; custom ekfc/gec[8] support; complete F-008 register
    readback verification with F-290 indirect_faulted fencing; all-zero
    keygen_scheme_clear() for byte-exact S1->S0 pcd-snapshot diff;
    keygen_scheme_read_spc() for per-class counters.
  - Extended F-266 soft-parser loader over parser code RAM [0x100..0x7fc]
    (16-byte / 4-word granularity, clear of F-266 [0x040..0x0b7]), 4-word
    position-independent direct-dispatch program {0x095F0300|sid, 0x00480001,
    0x1BFF0001, 0x1BFE0000} (or caller custom bytecode with optional scheme
    patch), bidirectional HXS mutual exclusion against F-266 punt slots and
    duplicate G4 slots, and bidirectional table-0 L4-protocol conflict guard
    against unreachable row-0 UDP/ESP rules (tc-flower, ntuple, WGFP).
  - Strict configure-before-enable attach with fail-closed reverse unwind
    (port faulted and downstream resources retained if any cleanup step fails),
    and fail-closed dual-SYNC detach (HXS disarm -> SYNC #1 -> parser restore
    -> KG unbind+all-zero clear -> SYNC #2 -> MURAM zero -> table free).
  - Strict F-321 per-port isolation preserved across primary + class tables;
    disarm preflight checks all active class tables on the port and
    __fman_pcd_fe_arm_disengage() detaches idle G4 classes before
    fman_pcd_kg_port_disarm_fe().

Applies after F-321/F-322. Idempotent; count-gated anchors.
"""

