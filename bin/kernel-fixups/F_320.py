"""F-320: contain DPAA FQ teardown failures and retain parent resources safely.

Fixes the DPAA half of T4 in drivers/net/ethernet/freescale/dpaa/dpaa_eth.{c,h}:
  * Hardens dpaa_fq_free_entry():
    - Skips retire/OOS/destroy for uncreated probe FQs (!fq->fqid).
    - Treats pending retirement (qman_retire_fq() > 0) as -EBUSY unconditionally
      (never gated on netif_msg_drv), returning without calling qman_oos_fq(),
      xdp_rxq_info_unreg(), qman_destroy_fq(), or list_del().
    - Retains the FQ on any retire or OOS error (nonempty, ORL, timeout) without
      unlinking or destroying it.
  * Converts FQ-backing parent allocations (dpaa_fq_alloc, dpaa_bp_alloc +
    percpu_count, priv->egress_fqs, priv->conf_fqs, priv->percpu_priv) off
    devm_* so driver core cannot auto-free them after a retained failure.
    (dpaa_alloc_offload_tx_fq_ics() retains devm_kzalloc on dev->dev.parent,
    which is the built-in non-removable mac_driver with suppress_bind_attrs.)
    Fixes dpaa_bp_free() NULL / FSL_DPAA_BPID_INV / shared-refcount handling.
  * In dpaa_eth_probe():
    - Passes &retain_failed_fq to dpaa_fq_init() so failed/timed-out FQ init
      retains the FQ instead of calling qman_destroy_fq().
    - Checks dpaa_fq_free() and retain_failed_fq on probe unwind; if unsettled,
      deactivates egress CGR callbacks, retains parent resources for this boot,
      and coerces -EPROBE_DEFER to a hard error so driver core cannot re-probe
      on top of retained hardware state.
    - On clean probe unwind, tears down flavor ops / NAPI only if registered,
      detaches flavor trackers before free_netdev(), and frees all non-devm
      parent allocations cleanly.
  * In dpaa_remove():
    - Returns early if dpaa_fq_free() fails, retaining CGRs, NAPI, flavor ops,
      BMan pool, non-devm parent allocations, and net_dev for this boot.
    - Frees non-devm parent allocations cleanly before free_netdev() on success.
  * Verifies dpaa_driver retains .suppress_bind_attrs = true.

Needs F-279, F-294, F-295, F-300, and F-316. Idempotent (marker); every anchor
must match exactly once.
"""

