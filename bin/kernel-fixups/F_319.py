#!/usr/bin/env python3
"""F-319: serialize QMan portal MC transactions, fence timeouts, and contain FQ shutdown.

Fixes T3 in drivers/soc/fsl/qbman/qman.c:
  * Adds a per-portal non-sleeping MC transaction lock (mc->lock,
    raw_spinlock_t) and permanent timeout fence (mc->wedged) to struct qm_mc.
  * Once qm_mc_result_timeout() times out on a committed command, mc->wedged is
    set so qm_mc_start() returns NULL before dpaa_zero(mc->cr), preventing CR
    overwrites and stale different-verb or same-verb RR acceptance.
  * Serializes all 11 MC-issuing functions in qman.c (all 15 qm_mc_start sites)
    with raw_spin_lock_irqsave(&p->p.mc.lock, irqflags) through response verb
    validation and result snapshotting, releasing mc->lock before logging or
    invoking callbacks (cgr->cb, fq->cb.fqs). Lock order: cgr_lock -> mc->lock.
  * Unmaps phys_fq in qman_init_fq() when mc->wedged prevents commit (and when
    HW rejects INITFQ with matching verb), without unmapping on timeout/desync.
  * Prevents permanent CSCI IRQ/workqueue storms in qm_congestion_task() on
    timeout or wedged MC, and validates both verb and QM_MCR_RESULT_OK.
  * Hardens qman_shutdown_fq():
    - Live portals (!qman_requires_cleanup()): only MC-only transitions
      (OOS, RETIRED->OOS, or PARKED with immediate empty/no-ORL retire->OOS);
      refuses with -EBUSY rather than hijacking live lockless SDQCR/DQRR/MR.
    - Boot cleanup (qman_requires_cleanup()): matches FQRN/FQRL by (verb, fqid),
      breaks out of MR scan on match so a following FQRL is not swallowed,
      captures msg->fq.fqs from matching FQRN into retire_fqs, drains FQRL on
      channel_portal, and bounds FQRN/VDQCR/FQRL waits with -ETIMEDOUT.

Needs F-297..F-306. Idempotent (marker); every anchor must match exactly once.
"""

