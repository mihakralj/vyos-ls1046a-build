def main():
    try:
        source = QMAN.read_text()
        if MARKER in source:
            for label, _, new in EDITS:
                if source.count(new) != 1:
                    raise ValueError(f"partially applied: {label}")
            print("### F-319: already applied")
            return 0
        for label, old, new in EDITS:
            count = source.count(old)
            if count != 1:
                raise ValueError(f"{label}: found {count} anchors, expected 1")
            source = source.replace(old, new, 1)
        QMAN.write_text(source)
    except (OSError, ValueError) as error:
        print(f"### F-319: FATAL: {error}", file=sys.stderr)
        return 1
    print(f"### F-319: QMan MC serialization, timeout fence, and shutdown protocol applied ({len(EDITS)} blocks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
